"""Write the TP Rounded character set: GB2312 + ASCII + common punctuation + kana + the extra files.

usage: python3 -I charset.py <out.txt> <extra.txt> [<extra.txt> ...]

The extra files are extra-chars.txt and the vocabularies build.ts orders the shards by (site-chars.txt,
catalog-title-chars.txt, hot-chars.txt), so none of their characters can be left out of the font.
Lines starting with # and whitespace are ignored.

GB2312 is generated by decoding every two-byte code in rows A1-F7 / cells A1-FE, so the list is
reproducible without a downloaded table. Python's codec maps A1A4 to U+30FB and A1AA to U+2015, so the
common Chinese forms (U+00B7, U+2014) are added explicitly below.
"""
import sys

RANGES = [
    (0x0020, 0x007E),  # ASCII
    (0x00A0, 0x00BF),  # Latin-1 punctuation: nbsp, ©, ®, °, ±, ·, ½ ...
    (0x00D7, 0x00D7),  # ×
    (0x00F7, 0x00F7),  # ÷
    (0x2010, 0x2027),  # dashes, quotes, bullet, ellipsis
    (0x2030, 0x203B),  # per mille, primes, single guillemets, reference mark
    (0x2190, 0x2193),  # arrows
    (0x21B5, 0x21B5),  # return arrow (command palette hint)
    (0x3000, 0x303F),  # CJK symbols and punctuation
    (0x3040, 0x30FF),  # hiragana + katakana
    (0xFF01, 0xFF5E),  # fullwidth ASCII forms
]


def gb2312():
    chars = set()
    for hi in range(0xA1, 0xF8):
        for lo in range(0xA1, 0xFF):
            try:
                chars.add(bytes([hi, lo]).decode("gb2312"))
            except UnicodeDecodeError:
                pass
    return chars


def main(out_path, *extra_paths):
    chars = gb2312()
    for a, b in RANGES:
        chars.update(chr(c) for c in range(a, b + 1))
    for extra_path in extra_paths:
        with open(extra_path, encoding="utf-8") as f:
            for line in f:
                if line.startswith("#"):
                    continue
                chars.update(c for c in line if not c.isspace())
    text = "".join(sorted(chars))
    with open(out_path, "w", encoding="utf-8") as f:
        f.write(text)
    print(f"charset: {len(text)} code points -> {out_path}")


if __name__ == "__main__":
    main(*sys.argv[1:])

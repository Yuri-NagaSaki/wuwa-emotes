#!/usr/bin/env bash
# Host firewall for the 潮池 server (nftables), IPv4 and IPv6.
#
# Inbound allowed: loopback, replies to our own connections, the ICMP/ICMPv6 messages a host needs
# (IPv6 neighbour discovery and router advertisements, which connection tracking does not cover),
# DHCP replies, SSH, and HTTPS (443) from Cloudflare's published ranges only. Everything else is dropped.
#
# Only the table `inet chaochi_fw` is touched, and only the input hook: Docker's own tables (container
# forwarding, NAT) are never flushed or modified. The table is replaced atomically on every apply.
# No container port is published (compose.yaml), so nothing reaches the server around this chain.
#
#   firewall.sh apply           load rules from the cached Cloudflare list, else the baked-in fallback
#   firewall.sh refresh         fetch the live lists, cache them, apply   (the weekly timer runs this)
#   firewall.sh fetch           fetch and cache only
#   firewall.sh print           print the ruleset `apply` would load
#   firewall.sh status          show the loaded table
#   firewall.sh install         install to /usr/local/sbin, boot + weekly systemd units, disable LLMNR,
#                               then refresh (run once before the first `docker compose up`)
#   firewall.sh disable-llmnr   turn off systemd-resolved LLMNR/mDNS (port 5355)
#   firewall.sh remove          delete the table: emergency only, inbound is wide open afterwards
#
# Settings (environment): CHAOCHI_SSH_PORT (22), CHAOCHI_FW_PORTS (443), CHAOCHI_FW_STATE
# (/var/lib/chaochi-firewall), CHAOCHI_FW_FALLBACK (cloudflare-ips.txt next to this script).
set -euo pipefail

TABLE=chaochi_fw
SSH_PORT=${CHAOCHI_SSH_PORT:-22}
PORTS=${CHAOCHI_FW_PORTS:-443}
STATE=${CHAOCHI_FW_STATE:-/var/lib/chaochi-firewall}
HERE=$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)
if [[ -z ${CHAOCHI_FW_FALLBACK:-} ]]; then
  for f in "$HERE/cloudflare-ips.txt" /usr/local/share/chaochi-firewall/cloudflare-ips.txt; do
    [[ -r $f ]] && { CHAOCHI_FW_FALLBACK=$f; break; }
  done
fi
FALLBACK=${CHAOCHI_FW_FALLBACK:-}
URL_V4=https://www.cloudflare.com/ips-v4
URL_V6=https://www.cloudflare.com/ips-v6

SBIN=/usr/local/sbin/chaochi-firewall
SHARE=/usr/local/share/chaochi-firewall
UNITS=/etc/systemd/system

log() { printf 'chaochi-firewall: %s\n' "$*" >&2; }
die() { log "error: $*"; exit 1; }

V4_RE='^([0-9]{1,3}\.){3}[0-9]{1,3}/[0-9]{1,2}$'
V6_RE='^[0-9a-fA-F:]+:[0-9a-fA-F:]*/[0-9]{1,3}$'

# keep only valid CIDRs of one family from stdin (comments and blank lines dropped)
filter_family() {
  local re=$1
  grep -Ev '^[[:space:]]*(#|$)' | tr -d ' \r\t' | grep -E "$re" || true
}

# ranges <v4|v6>: cached live list if present and sane, otherwise the baked-in fallback
ranges() {
  local fam=$1 re min cached
  if [[ $fam == v4 ]]; then re=$V4_RE min=10; else re=$V6_RE min=5; fi
  cached=$STATE/ips-$fam
  if [[ -r $cached ]] && (($(filter_family "$re" <"$cached" | wc -l) >= min)); then
    filter_family "$re" <"$cached"
    return
  fi
  [[ -n $FALLBACK && -r $FALLBACK ]] || die "no cached list in $STATE and no fallback file (cloudflare-ips.txt)"
  filter_family "$re" <"$FALLBACK"
}

join_commas() { paste -sd, - | sed 's/,/, /g'; }

render() {
  local v4 v6
  v4=$(ranges v4 | join_commas)
  v6=$(ranges v6 | join_commas)
  [[ -n $v4 && -n $v6 ]] || die "empty Cloudflare range list"
  cat <<EOF
# generated by chaochi-firewall; edit deploy/firewall.sh, not this output
table inet $TABLE
delete table inet $TABLE
table inet $TABLE {
	set cloudflare_v4 {
		type ipv4_addr
		flags interval
		elements = { $v4 }
	}

	set cloudflare_v6 {
		type ipv6_addr
		flags interval
		elements = { $v6 }
	}

	chain input {
		type filter hook input priority filter; policy drop;

		iif "lo" accept
		ct state established,related accept
		ct state invalid drop

		# IPv6 cannot work without neighbour discovery and router advertisements (not tracked by conntrack)
		icmpv6 type { nd-neighbor-solicit, nd-neighbor-advert, nd-router-advert, nd-router-solicit, packet-too-big, destination-unreachable, time-exceeded, parameter-problem } accept
		# DHCP replies, so a DHCP-configured server keeps its address
		udp sport 67 udp dport 68 accept
		udp sport 547 udp dport 546 accept

		tcp dport $SSH_PORT accept comment "ssh"
		ip saddr @cloudflare_v4 tcp dport { $PORTS } accept comment "https from Cloudflare"
		ip6 saddr @cloudflare_v6 tcp dport { $PORTS } accept comment "https from Cloudflare"

		counter comment "dropped"
	}
}
EOF
}

# refuse to lock out SSH: if sshd is listening, SSH_PORT must be one of its ports
check_ssh() {
  local ports
  ports=$({ ss -Hltnp 2>/dev/null || true; } | awk '/"sshd"/ { n = split($4, a, ":"); print a[n] }' | sort -u)
  [[ -z $ports ]] && return 0
  grep -qx "$SSH_PORT" <<<"$ports" && return 0
  [[ ${CHAOCHI_FW_FORCE:-0} == 1 ]] && { log "warning: sshd listens on $(tr '\n' ' ' <<<"$ports")but SSH_PORT=$SSH_PORT (forced)"; return 0; }
  die "sshd listens on port(s) $(tr '\n' ' ' <<<"$ports")but CHAOCHI_SSH_PORT=$SSH_PORT; set it (or CHAOCHI_FW_FORCE=1)"
}

apply() {
  ((EUID == 0)) || die "run as root"
  command -v nft >/dev/null || die "nft not found (apt install nftables)"
  check_ssh
  local rules
  rules=$(mktemp)
  render >"$rules"
  nft -c -f "$rules" || { rm -f "$rules"; die "ruleset rejected by nft -c; nothing changed"; }
  nft -f "$rules"
  rm -f "$rules"
  log "applied: ssh $SSH_PORT open; tcp $PORTS from $(ranges v4 | wc -l) IPv4 + $(ranges v6 | wc -l) IPv6 Cloudflare ranges; all other inbound dropped"
}

fetch() {
  command -v curl >/dev/null || die "curl not found"
  mkdir -p "$STATE"
  local fam url re min tmp n
  for fam in v4 v6; do
    if [[ $fam == v4 ]]; then url=$URL_V4 re=$V4_RE min=10; else url=$URL_V6 re=$V6_RE min=5; fi
    tmp=$(mktemp "$STATE/.ips-$fam.XXXXXX")
    if ! curl -fsS --max-time 20 --retry 3 --retry-delay 5 "$url" -o "$tmp"; then
      rm -f "$tmp"
      log "warning: could not fetch $url; keeping the previous list"
      return 75
    fi
    n=$(filter_family "$re" <"$tmp" | wc -l)
    if ((n < min)) || (($(grep -Evc '^[[:space:]]*$' "$tmp") != n)); then
      rm -f "$tmp"
      log "warning: $url returned an unexpected list ($n valid lines); keeping the previous list"
      return 75
    fi
    # store one CIDR per line, newline-terminated (Cloudflare serves the lists without a final newline)
    filter_family "$re" <"$tmp" >"$tmp.clean"
    rm -f "$tmp"
    chmod 644 "$tmp.clean"
    mv -f "$tmp.clean" "$STATE/ips-$fam"
  done
  log "fetched Cloudflare ranges: $(wc -l <"$STATE/ips-v4") IPv4, $(wc -l <"$STATE/ips-v6") IPv6"
  if [[ -n $FALLBACK && -r $FALLBACK ]]; then
    if ! diff -q <(cat "$STATE/ips-v4" "$STATE/ips-v6" | filter_family '.' | sort) \
      <(filter_family '.' <"$FALLBACK" | sort) >/dev/null; then
      log "notice: the live list differs from $FALLBACK; update deploy/cloudflare-ips.txt (Caddy trusts CF-Connecting-IP from it)"
    fi
  fi
}

disable_llmnr() {
  ((EUID == 0)) || die "run as root"
  install -d /etc/systemd/resolved.conf.d
  printf '[Resolve]\nLLMNR=no\nMulticastDNS=no\n' >/etc/systemd/resolved.conf.d/90-chaochi-no-llmnr.conf
  if systemctl is-active --quiet systemd-resolved 2>/dev/null; then
    systemctl restart systemd-resolved
    log "systemd-resolved: LLMNR and mDNS off (port 5355 closed)"
  else
    log "systemd-resolved not running; drop-in written for when it starts"
  fi
}

# write the systemd units into a directory (install uses /etc/systemd/system)
write_units() {
  local dir=$1
  mkdir -p "$dir"
  cat >"$dir/chaochi-firewall.service" <<EOF
[Unit]
Description=潮池 host firewall (nftables table inet $TABLE)
Documentation=file://$SBIN
DefaultDependencies=no
Wants=network-pre.target
Before=network-pre.target shutdown.target
Conflicts=shutdown.target
After=local-fs.target
RequiresMountsFor=/usr/local /var/lib

[Service]
Type=oneshot
RemainAfterExit=yes
ExecStart=$SBIN apply
ExecReload=$SBIN apply

[Install]
WantedBy=sysinit.target
EOF
  cat >"$dir/chaochi-firewall-refresh.service" <<EOF
[Unit]
Description=潮池 host firewall: refresh Cloudflare ranges
Wants=network-online.target
After=network-online.target chaochi-firewall.service

[Service]
Type=oneshot
ExecStart=$SBIN refresh
EOF
  cat >"$dir/chaochi-firewall-refresh.timer" <<EOF
[Unit]
Description=Weekly refresh of Cloudflare ranges for the 潮池 firewall

[Timer]
OnCalendar=weekly
RandomizedDelaySec=6h
Persistent=true

[Install]
WantedBy=timers.target
EOF
}

install_all() {
  ((EUID == 0)) || die "run as root"
  command -v nft >/dev/null || die "nft not found (apt install nftables)"
  if systemctl is-enabled --quiet nftables 2>/dev/null && grep -q 'flush ruleset' /etc/nftables.conf 2>/dev/null; then
    log "warning: nftables.service is enabled and /etc/nftables.conf flushes the whole ruleset, Docker's rules included;"
    log "         disable it (systemctl disable nftables) or remove 'flush ruleset'"
  fi
  for svc in ufw firewalld; do
    systemctl is-active --quiet "$svc" 2>/dev/null && log "warning: $svc is active; it may conflict with this firewall"
  done
  install -D -m 0755 "${BASH_SOURCE[0]}" "$SBIN"
  [[ -n $FALLBACK ]] && install -D -m 0644 "$FALLBACK" "$SHARE/cloudflare-ips.txt"
  write_units "$UNITS"
  systemctl daemon-reload
  systemctl enable chaochi-firewall.service
  systemctl enable --now chaochi-firewall-refresh.timer
  disable_llmnr
  CHAOCHI_FW_FALLBACK=$SHARE/cloudflare-ips.txt "$SBIN" refresh || "$SBIN" apply
  systemctl start chaochi-firewall.service
  log "installed: $SBIN, chaochi-firewall.service (boot), chaochi-firewall-refresh.timer (weekly)"
}

cmd=${1:-}
case $cmd in
  apply) apply ;;
  refresh)
    rc=0
    fetch || rc=$?
    apply
    exit "$rc"
    ;;
  fetch) fetch ;;
  print) render ;;
  status) nft list table inet "$TABLE" ;;
  install) install_all ;;
  disable-llmnr) disable_llmnr ;;
  remove)
    ((EUID == 0)) || die "run as root"
    nft delete table inet "$TABLE" 2>/dev/null || true
    log "table inet $TABLE removed: inbound traffic is no longer filtered"
    ;;
  units) write_units "${2:?units <dir>}" ;; # for review and tests
  *) sed -n '2,24p' "$0" | sed 's/^# \{0,1\}//' >&2; exit 64 ;;
esac
